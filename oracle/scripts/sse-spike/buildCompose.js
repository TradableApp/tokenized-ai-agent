'use strict';
// Writes rofl/compose.yaml for the probe's own ROFL app, with probeServer.js pasted in as
// the container's `node -e` program. No image is built: the container is the stock public
// Node image, pinned by digest, and the program travels inside the compose file, which the
// ROFL bundle carries. Run after any change to probeServer.js:
//
//   node oracle/scripts/sse-spike/buildCompose.js
//
// A test fails if the committed compose file and this output differ.
const fs = require('node:fs');
const path = require('node:path');

// docker.io/library/node, tag 24-alpine, multi-platform index digest read from Docker Hub's
// public tag metadata on 2026-11-21 (last pushed 2026-11-11). The platform line below
// picks the linux/amd64 image from that index.
const IMAGE =
  'docker.io/library/node:24-alpine@sha256:116b800c3754b440ee0aa3ed2f20f5bf3d99a554bfd9adeea09ea8017f6e85f5';
const PORT = 8787;
// The sandbox dApp (Firebase hosting site sense-ai-app-garrick), the local dApp dev server,
// and the local static server for probe.html (RUNBOOK step "browser check").
const ALLOWED_ORIGINS = [
  'https://sense-ai-app-garrick.web.app',
  'https://sense-ai-app-garrick.firebaseapp.com',
  'http://localhost:3002',
  'http://127.0.0.1:8788',
];

function renderCompose(source) {
  if (source.includes(String.fromCharCode(36))) {
    throw new Error('probeServer.js contains a dollar sign; compose would read it as a variable');
  }
  const body = source
    .replace(/\n+$/, '')
    .split('\n')
    .map((line) => (line.length > 0 ? '        ' + line : ''))
    .join('\n');
  return [
    '# Generated by ../buildCompose.js from ../probeServer.js. Do not edit by hand.',
    '# A throwaway measurement app: no secrets, no volumes, no image build.',
    'services:',
    '  probe:',
    '    image: ' + IMAGE,
    '    platform: linux/amd64',
    '    restart: on-failure',
    '    ports:',
    '      - "' + PORT + ':' + PORT + '"',
    '    environment:',
    '      - PROBE_PORT=' + PORT,
    '      - PROBE_ALLOWED_ORIGINS=' + ALLOWED_ORIGINS.join(','),
    '    entrypoint:',
    '      - node',
    '      - -e',
    '      - |',
    body,
    '',
  ].join('\n');
}

module.exports = { renderCompose, IMAGE, PORT, ALLOWED_ORIGINS };

if (require.main === module) {
  const dir = __dirname;
  const out = renderCompose(fs.readFileSync(path.join(dir, 'probeServer.js'), 'utf8'));
  fs.writeFileSync(path.join(dir, 'rofl', 'compose.yaml'), out);
  console.log('wrote rofl/compose.yaml (' + out.length + ' bytes)');
}
